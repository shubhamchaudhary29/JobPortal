#!/usr/bin/env bash
# Regenerate frontend/cloudflare-realip.conf from Cloudflare's published edge ranges (GEO-7C).
#
#   bash frontend/scripts/update-cloudflare-ips.sh [--out FILE]
#
# nginx trusts CF-Connecting-IP only from these ranges, so the list must be current: run this when Cloudflare
# announces a change (https://www.cloudflare.com/ips/), commit the diff and redeploy. The same ranges are the
# AWS security-group allow-list for ports 80/443 (docs/geo-operations.md, "Own domain and Cloudflare").
# Fails without writing anything when a download is empty or any line is not a CIDR.
set -euo pipefail

OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/cloudflare-realip.conf"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --out) OUT="$2"; shift 2 ;;
    *) printf 'Unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

fetch() {
  curl --fail --silent --show-error --location --max-time 30 "$1" -o "$2"
  # Normalize: strip CR and blank lines; the files end without a trailing newline.
  tr -d '\r' < "$2" | sed '/^[[:space:]]*$/d' > "$2.clean"
  [[ -s "$2.clean" ]] || { printf 'Empty download: %s\n' "$1" >&2; exit 1; }
}

fetch https://www.cloudflare.com/ips-v4 "$work/v4"
fetch https://www.cloudflare.com/ips-v6 "$work/v6"

ipv4='^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$'
ipv6='^[0-9a-fA-F:]*:[0-9a-fA-F:]*/([0-9]|[1-9][0-9]|1[01][0-9]|12[0-8])$'
if bad=$(grep -Ev "$ipv4" "$work/v4.clean"); then printf 'Not an IPv4 CIDR: %s\n' "$bad" >&2; exit 1; fi
if bad=$(grep -Ev "$ipv6" "$work/v6.clean"); then printf 'Not an IPv6 CIDR: %s\n' "$bad" >&2; exit 1; fi

{
  printf '# Cloudflare edge ranges: nginx restores the visitor address from CF-Connecting-IP only for requests\n'
  printf '# that arrive from these ranges (GEO-7C). Enabled by CLOUDFLARE_PROXY=true (select-nginx-config.sh).\n'
  printf '# Generated by frontend/scripts/update-cloudflare-ips.sh on %s from\n' "$(date -u +%Y-%m-%d)"
  printf '# https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6. Do not edit by hand.\n\n'
  while read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done < "$work/v4.clean"
  while read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done < "$work/v6.clean"
  printf '\nreal_ip_header CF-Connecting-IP;\nreal_ip_recursive on;\n'
} > "$work/out"

mv "$work/out" "$OUT"
printf 'Wrote %s (%d IPv4, %d IPv6 ranges)\n' "$OUT" "$(wc -l < "$work/v4.clean")" "$(wc -l < "$work/v6.clean")"
